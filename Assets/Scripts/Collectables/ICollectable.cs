/// <summary>
/// Интерфейс "подбираемый предмет".
/// Интерфейс — это "договор": любой класс, который его реализует,
/// ОБЯЗАН иметь метод Collect. Благодаря этому игре не важно,
/// монета это, сердечко или что-то новое — у всех есть Collect().
/// </summary>
public interface ICollectable
{
    /// <summary>Что происходит, когда игрок подобрал предмет.</summary>
    void Collect(PlayerController player);
}
