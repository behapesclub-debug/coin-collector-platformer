/// <summary>
/// Карты уровней в виде текста. Один символ = одна клетка 1×1 метр (Unity unit).
/// Меняй символы → запусти меню "Platformer → Собрать игру" → уровень пересоберётся.
///
/// Легенда:
///   #  земля / стена (твёрдая)          P  старт игрока
///   C  монета                            H  сердечко (+1 жизнь)
///   ^  шипы (опасность)                  K  чекпоинт
///   F  финиш                             =  платформа, ездит вправо на 4 клетки
///   ~  платформа, ездит вверх на 4 клетки
///   пробел — пусто. Дыра в нижних рядах "#" = яма (упал — минус жизнь).
///
/// Прыжок игрока: примерно 3,5 клетки вверх и 6–7 клеток в длину.
